replaceDef('spitter', spitter, 24, 24);
replaceDef('pouncer', pouncer, 20, 24);
replaceDef('vomiter', vomiter, 24, 26);
replaceDef('brute', brute, 32, 36);
replaceDef('boss', boss, 32, 36);

