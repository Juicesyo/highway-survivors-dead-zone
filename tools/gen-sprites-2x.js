/** 自动居中的一行：Cw(画布宽, [字符, 次数], ...) */
function Cw(w, ...pairs) {
  const body = pairs.map(([ch, n]) => ch.repeat(n)).join('');
  if (body.length > w) throw new Error('行超宽 ' + body.length + '/' + w + ' : ' + body);
  const pad = w - body.length;
  const left = pad >> 1;
  return '.'.repeat(left) + body + '.'.repeat(pad - left);
}

