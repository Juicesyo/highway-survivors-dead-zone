/* ---------- 写回 spriteDefs.js ---------- */

let src = fs.readFileSync(FILE, 'utf8');
const NL = src.indexOf('\r\n') >= 0 ? '\r\n' : '\n';
const RL = NL === '\r\n' ? '\r?\\n' : '\\n';

function replaceDef(name, rows, w, h) {
  if (rows.length !== h) throw new Error(name + ' 行数 ' + rows.length + ' != ' + h);
  rows.forEach((r, i) => {
    if (r.length !== w) throw new Error(name + ' 第 ' + i + ' 行宽 ' + r.length + ' != ' + w + ' : ' + r);
  });
  const re = new RegExp(
    '(' + name + ': \\{' + RL + '      )w: \\d+, h: \\d+,(?: px: \\d+,)?(' + RL +
    '      pal: \\{[\\s\\S]*?\\},' + RL + '      rows: \\[' + RL + ')([\\s\\S]*?)(' + RL +
    '      \\]' + RL + '    \\})'
  );
  if (!re.test(src)) throw new Error('找不到定义: ' + name);
  const body = rows.map(r => "        '" + r + "'").join(',' + NL);
  src = src.replace(re, '$1' + 'w: ' + w + ', h: ' + h + ', px: 2,$2' + body + '$4');
}

replaceDef('player', player, 24, 28);
